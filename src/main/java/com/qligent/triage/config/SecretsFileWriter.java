package com.qligent.triage.config;

import java.io.IOException;
import java.io.Writer;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.LinkedHashMap;
import java.util.Map;

import org.springframework.stereotype.Component;
import org.yaml.snakeyaml.DumperOptions;
import org.yaml.snakeyaml.Yaml;

@Component
public class SecretsFileWriter {

	private final Path secretsPath = Path.of("./secrets.yaml");

	public void write(String zephyrApiToken, String jiraApiUrl, String jiraEmail, String jiraApiToken)
			throws IOException {
		Map<String, Object> root = new LinkedHashMap<>();
		root.put("zephyr", Map.of("api-token", zephyrApiToken != null ? zephyrApiToken : ""));

		Map<String, Object> jira = new LinkedHashMap<>();
		if (jiraApiUrl != null && !jiraApiUrl.isBlank()) {
			jira.put("api-url", jiraApiUrl.trim());
		}
		if (jiraEmail != null && !jiraEmail.isBlank()) {
			jira.put("email", jiraEmail.trim());
		}
		if (jiraApiToken != null && !jiraApiToken.isBlank()) {
			jira.put("api-token", jiraApiToken.trim());
		}
		root.put("jira", jira);

		DumperOptions options = new DumperOptions();
		options.setDefaultFlowStyle(DumperOptions.FlowStyle.BLOCK);
		Yaml yaml = new Yaml(options);

		try (Writer writer = Files.newBufferedWriter(secretsPath)) {
			writer.write("# Auto-generated by Triage setup\n");
			writer.write("# Copy from secrets.example.yaml for reference\n\n");
			yaml.dump(root, writer);
		}
	}
}
